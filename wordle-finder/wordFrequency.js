/**
 * Get the frequency rank of a word (lower = more common)
 * Wordle answers get a bonus (divided by 2)
 */
function getWordFrequency(word) {
  var baseRank = window.wordFrequency[word] || 10000;
  // Boost Wordle answers significantly
  if (window.wordleAnswers.has(word)) {
    return Math.min(baseRank, 500); // Cap at 500 for known answers
  }
  return baseRank;
}

/**
 * Check if a word is a known Wordle answer
 */
function isWordleAnswer(word) {
  return window.wordleAnswers.has(word);
}
